const clean = (s) => String(s || "").replace(/[־\-–,.()]/g, " ").replace(/\s+/g, " ").trim();

/* Longest name first, so "קריית אונו" is not mistaken for something shorter. */
const NAMES = Object.keys(CITIES).sort((a, b) => b.length - a.length);

/* The coordinates of the first known city named in a piece of text, or null. */
export function place(text) {
  const t = clean(text);
  for (const name of NAMES) if (t.includes(name)) return { name, at: CITIES[name] };
  return null;
}

export function km(a, b) {
  const rad = (d) => (d * Math.PI) / 180;
  const dLat = rad(b[0] - a[0]);
  const dLon = rad(b[1] - a[1]);
  const h = Math.sin(dLat / 2) ** 2 + Math.cos(rad(a[0])) * Math.cos(rad(b[0])) * Math.sin(dLon / 2) ** 2;
  return 2 * 6371 * Math.asin(Math.sqrt(h));
}
