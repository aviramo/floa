// בלי מרקדאון, בלי מקפים ארוכים, בלי גרשיים מסולסלים וזוויתיים, בלי שלוש נקודות מיוחדות, חצים, תבליטים וסימנים מיוחדים,
// ובלי אימוג'ים מלבד פרצוף מחייך פשוט. מקף רגיל בין מילים מטופל ב-parse.ts (הופך לפסיק).
export function humanize(input: string): string {
  let t = String(input ?? '');
  // תווים נסתרים ורווח קשיח
  t = t.replace(/[​-‏‪-‮⁠﻿]/g, '').replace(/ /g, ' ');
  // מרקדאון: הדגשה, קוד, כותרות, תבליטים ורשימות ממוספרות
  t = t.replace(/\*\*?([^*\n]+)\*\*?/g, '$1').replace(/__?([^_\n]+)__?/g, '$1').replace(/`+/g, '').replace(/^#{1,6}\s*/gm, '');
  t = t.replace(/^\s*[-*•●▪‣]\s+/gm, '').replace(/^\s*\d+[.)]\s+/gm, '');
  // גרשיים מסולסלים וזוויתיים וגרשיים עבריים הופכים לרגילים
  t = t.replace(/[“”„«»״]/g, '"').replace(/[‘’‚׳]/g, "'");
  // שלוש נקודות (כולל התו המיוחד) הופכות לנקודה אחת
  t = t.replace(/…/g, '.').replace(/\.{3,}/g, '.');
  // חצים וסימנים גרפיים
  t = t.replace(/[←-⇿─-➿⬀-⯿]/g, ' ');
  // אימוג'ים: משאירים רק 🙂 ו-😊
  t = t.replace(/[\u{1F300}-\u{1FAFF}☀-⛿✀-➿️]/gu, (e) => (e === '\u{1F642}' || e === '\u{1F60A}' ? e : ''));
  // רווחים
  t = t.replace(/[ \t]{2,}/g, ' ').replace(/ +([,.?!:])/g, '$1');
  return t.trim();
}
